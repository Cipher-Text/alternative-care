"""Shared PDF rendering for clinical documents (prescriptions, invoices).

HTML is rendered to PDF with WeasyPrint, which shapes Bengali conjuncts correctly through
Pango/HarfBuzz (ReportLab does not). Documents are generated on demand and streamed to the
caller: nothing is stored, so there are no stale links, no object-storage dependency and tenant
isolation is simply "the endpoint that built it".

System requirements (not pip-installable):
- Pango (+ its GLib/Cairo dependencies). The Docker image installs them; on macOS use
  `brew install pango` — this module adds Homebrew's lib directory to the loader path itself.
- A font with Bengali glyphs (Noto Sans Bengali on Linux via `fonts-noto-core`; macOS ships
  Kohinoor Bangla / Bangla Sangam MN). Latin and Bengali glyphs fall back per character, so the
  stack below lists a Latin face first and the Bengali faces after it.
"""

from __future__ import annotations

import asyncio
import os
import sys
from html import escape

import structlog
from fastapi import HTTPException, status

logger = structlog.get_logger(__name__)

# macOS: dlopen ignores Homebrew's prefix unless it is on the fallback path.
_MAC_LIB_DIRS = ("/opt/homebrew/lib", "/usr/local/lib")


def _ensure_native_libs() -> None:
    if sys.platform != "darwin":
        return
    current = os.environ.get("DYLD_FALLBACK_LIBRARY_PATH", "")
    extra = [d for d in _MAC_LIB_DIRS if os.path.isdir(d) and d not in current.split(":")]
    if extra:
        os.environ["DYLD_FALLBACK_LIBRARY_PATH"] = ":".join(filter(None, [current, *extra]))


def pdf_available() -> bool:
    """True when WeasyPrint and its native libraries can be loaded."""
    try:
        _ensure_native_libs()
        import weasyprint  # noqa: F401

        return True
    except (ImportError, OSError):
        return False


def _render_sync(html: str) -> bytes:
    _ensure_native_libs()
    from weasyprint import HTML

    return HTML(string=html).write_pdf()


async def render_pdf(html: str) -> bytes:
    """Render an HTML document to PDF bytes without blocking the event loop."""
    try:
        return await asyncio.to_thread(_render_sync, html)
    except (ImportError, OSError) as exc:
        logger.error("pdf_rendering_unavailable", error=str(exc))
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="PDF rendering is not available on this server.",
        ) from exc


# ----- HTML helpers --------------------------------------------------------------------------


def esc(value: object) -> str:
    """Escape any value for safe inclusion in HTML ('' for None)."""
    return escape("" if value is None else str(value), quote=True)


def multiline(value: str | None) -> str:
    """Escape free text and keep its line breaks."""
    return esc(value).replace("\r\n", "\n").replace("\n", "<br>")


def label(en: str, bn: str) -> str:
    """A bilingual field label: English first, Bengali after."""
    return f'{esc(en)} <span class="bn">/ {esc(bn)}</span>'


