def document(title: str, body: str) -> str:
    """Wrap a body fragment in a complete HTML document with the shared stylesheet."""
    return (
        "<!doctype html><html><head><meta charset='utf-8'>"
        f"<title>{esc(title)}</title><style>{BASE_CSS}</style></head><body>"
        f"{body}</body></html>"
    )
